// ─── Plant ────────────────────────────────────────────────────────────────────


export type LightCondition = 'cień' | 'półcień' | 'jasne' | 'pełne słońce'

export interface Plant {
  id?: number
  name: string
  species?: string
  room: string
  notes?: string
  imageBase64?: string
  wateringIntervalDays?: number
  fertilizingIntervalDays?: number
  mistingIntervalDays?: number
  cleaningIntervalDays?: number
  /** Key into PlantTemplate.species — the linked species template */
  templateSpecies?: string
  /** Light exposure of this specific plant (independent of the room) */
  lightCondition?: LightCondition
  createdAt: Date
  archivedAt?: Date
  /** Whether the monthly survey is enabled (undefined = true — enabled by default) */
  surveyEnabled?: boolean
}

/** A plant definitely saved in the database — has an id */
export type StoredPlant = Required<Pick<Plant, 'id'>> & Omit<Plant, 'id'>

/** Data to create a new plant (without fields generated by the database) */
export type NewPlant = Omit<Plant, 'id' | 'createdAt'>

/** Partial plant update (without system fields) */
export type PlantUpdate = Partial<NewPlant>

