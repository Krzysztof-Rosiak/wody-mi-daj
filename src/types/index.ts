/** Care types that have intervals (overdue days can be calculated) */
export type ScheduledCareType = Extract<CareType, 'watering' | 'fertilizing' | 'misting' | 'cleaning'>

// ─── CareEvent ────────────────────────────────────────────────────────────────

export interface CareEvent {
  id?: number
  plantId: number
  type: CareType
  date: Date
  notes?: string
}

/** An event definitely saved in the database */
export type StoredCareEvent = Required<Pick<CareEvent, 'id'>> & Omit<CareEvent, 'id'>

/** Data to create a new event */
export type NewCareEvent = Omit<CareEvent, 'id'>

// ─── CareStatus ───────────────────────────────────────────────────────────────

/** Care status of a plant for a given type */
export type CareStatus = 'ok' | 'due' | 'overdue' | 'never'

export interface CareStatusInfo {
  status: CareStatus
  /** Date of the last event of this type (undefined = never) */
  lastDate?: Date
  /** Number of days since the last event (undefined = never) */
  daysSinceLast?: number
  /** Number of overdue days (positive = overdue, negative = too early) */
  daysOverdue?: number
}

/** Map of care statuses for all types that have an interval */
export type PlantCareStatuses = Record<ScheduledCareType, CareStatusInfo>

// ─── PlantWateringStatus ──────────────────────────────────────────────────────

/** Watering status of a specific plant */
export interface PlantWateringStatus {
  plant: Plant
  /** Number of days since the last watering (null = never watered) */
  daysSince: number | null
  /** Watering interval in days */
  interval: number
  /** Days past due (negative = before due date, 999 = never watered) */
  overdueDays: number
}

// ─── TaskItem ─────────────────────────────────────────────────────────────────

/** Item in the care task list */
export interface TaskItem {
  plant: Plant
  /** Number of days since the last care of this type (null = never) */
  daysSince: number | null
  /** Days past due (0 = due exactly today) */
  overdue: number
}

// ─── DoneItem ─────────────────────────────────────────────────────────────────

/** An event with its associated plant (for the "done today" list) */
export interface DoneItem {
  event: CareEvent
  plant: Plant | undefined
}

// ─── CustomRoom ───────────────────────────────────────────────────────────────

/** A room added by the user (defaults are hardcoded) */
export interface CustomRoom {
  id?: number
  name: string
}

